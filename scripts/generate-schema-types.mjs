import { compile } from "json-schema-to-typescript";
import { readFileSync, writeFileSync } from "fs";
import { resolve } from "path";
import { fileURLToPath } from "url";

const repoRoot = resolve(fileURLToPath(import.meta.url), "../..");
const schemaDir = resolve(repoRoot, "submodules/datam8-generator/datam8-model/schema");
const outputFile = resolve(repoRoot, "apps/web/src/features/model/generated-schema-types.ts");

// Process in dependency order so cross-file $refs resolve correctly
const schemaFiles = [
  "common.json",
  "property.json",
  "data-type.json",
  "data-source.json",
  "attribute.json",
  "zone.json",
  "folder.json",
  "data-product.json",
  "model.json",
  "plugin.json",
  "solution.json",
  "base.json",
  "diagram.json",
];

const banner = `// DO NOT EDIT — generated by scripts/generate-schema-types.mjs
// Source: submodules/datam8-generator/datam8-model/schema/
// Regenerate: npm run generate:schema-types
`;

/**
 * Parse a compiled TypeScript block into individual top-level declarations.
 * Returns an array of { name, text } where name is the identifier and text is
 * the full declaration including any preceding JSDoc comment.
 */
function extractDeclarations(source) {
  // Strip any leading banner comment
  const stripped = source.replace(/^\/\*[\s\S]*?\*\/\s*/m, "").trimStart();

  // Split into top-level declaration blocks by splitting on lines that start
  // a new export (but keeping the delimiter as part of the next block).
  // We also keep JSDoc comments attached to the declaration that follows them.
  const blocks = [];
  const lines = stripped.split("\n");
  let current = [];

  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];
    const isExportLine = /^export\s+(interface|type|enum)\s+/.test(line);

    if (isExportLine && current.length > 0) {
      // Check if current block is a JSDoc-only fragment (i.e. previous export's
      // body hasn't started yet — shouldn't happen, but guard anyway)
      blocks.push(current.join("\n").trim());
      current = [];
    }

    current.push(line);
  }

  if (current.length > 0) {
    blocks.push(current.join("\n").trim());
  }

  // Now parse each block to extract the identifier
  const declarations = [];
  for (const block of blocks) {
    if (!block) continue;
    const match = block.match(/export\s+(?:interface|type|enum)\s+(\w+)/);
    if (match) {
      declarations.push({ name: match[1], text: block });
    }
  }

  return declarations;
}

const parts = [];
const seen = new Set();

for (const file of schemaFiles) {
  const schema = JSON.parse(readFileSync(resolve(schemaDir, file), "utf8"));
  const result = await compile(schema, "", {
    bannerComment: "",
    cwd: schemaDir,
    unreachableDefinitions: true,
    format: true,
  });

  const declarations = extractDeclarations(result);
  const unique = declarations.filter(({ name }) => {
    if (seen.has(name)) return false;
    seen.add(name);
    return true;
  });

  if (unique.length > 0) {
    parts.push(`// ---- ${file} ----\n`);
    parts.push(unique.map((d) => d.text).join("\n\n"));
    parts.push("");
  }
}

writeFileSync(outputFile, banner + "\n" + parts.join("\n"), "utf8");
console.log(`Generated: ${outputFile}`);
